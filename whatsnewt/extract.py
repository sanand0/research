"""Regenerate the self-contained walkthrough data from a pinned whatsnewt checkout.

Usage: uv run extract.py /path/to/whatsnewt-clone
This executes all 18 reference solutions using the game's own checkers. It
temporarily redirects autosaves, so it never touches a player's saved game.
"""
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

upstream = Path(sys.argv[1]).resolve()
sys.path[:0] = [str(upstream / "src"), str(upstream / "tests")]

from solutions import SOLUTIONS  # noqa: E402
from test_playthrough import WALK  # noqa: E402
from whatsnewt.challenges import PUZZLES  # noqa: E402
from whatsnewt.engine import COUNCIL, CURIOSITIES, Game, _ZEN_NOTES, _aphorisms  # noqa: E402
from whatsnewt.world import ITEMS, ROOMS, SIGILS  # noqa: E402

data = {
    "source": "https://gitlab.com/flufl/whatsnewt",
    "commit": subprocess.check_output(
        ["git", "-C", str(upstream), "rev-parse", "HEAD"], text=True
    ).strip(),
    "rooms": {},
    "puzzles": {},
    "items": {},
    "route": [],
    "secrets": {},
    "council": list(COUNCIL),
    "zen": [{"saying": saying, "note": _ZEN_NOTES.get(saying)} for saying in _aphorisms()],
}

for key, room in ROOMS.items():
    data["rooms"][key] = {
        "name": room.name, "subtitle": room.subtitle, "label": room.label,
        "blurb": room.blurb, "description": room.description,
        "exits": room.exits, "details": room.details,
        "items": list(room.items), "puzzles": list(room.puzzles),
        "column": room.column, "row": room.row, "level": room.level,
    }

for key, item in ITEMS.items():
    data["items"][key] = {
        "name": item.name, "description": item.description, "sigil": item.sigil
    }

for key, puzzle in PUZZLES.items():
    data["puzzles"][key] = {
        "title": puzzle.title, "citation": puzzle.citation,
        "briefing": puzzle.briefing, "starter": puzzle.starter,
        "hints": list(puzzle.hints), "points": puzzle.points,
        "reward": puzzle.reward, "language": puzzle.language,
        "anchor": puzzle.anchor, "docs": puzzle.docs,
        "solution": SOLUTIONS[key],
    }

with tempfile.TemporaryDirectory(prefix="whatsnewt-walk-") as state_home:
    os.environ["XDG_STATE_HOME"] = state_home
    game = Game()
    visited = set()
    for command, extra in WALK:
        if command != "foyer":
            assert not game.execute(command).ending
        room = game.here
        fresh = room.key not in visited
        visited.add(room.key)
        for action in extra:
            game.execute(action)
        answered = []
        if fresh:
            for key in room.puzzles:
                verdict, _ = game.submit(key, SOLUTIONS[key])
                assert verdict.solved, (key, verdict.message)
                answered.append(key)
        data["route"].append({
            "room": room.key,
            "via": command,
            "collect": [action.removeprefix("take ") for action in extra],
            "answer": answered,
            "first": fresh,
            "score": game.score,
            "sigils": len(game.sigils),
        })
    assert game.finished and game.room == "gate"
    assert game.visited == set(ROOMS)
    assert game.solved == set(PUZZLES)
    assert set(game.carrying) == set(ITEMS)
    assert game.score == game.possible() == 375

    for key, (label, lines) in CURIOSITIES.items():
        response = game.execute(key)
        data["secrets"][key] = {
            "label": label,
            "response": [line.text for line in response.lines],
            "council": key in COUNCIL,
        }
    assert set(game.curiosities) == set(CURIOSITIES)
    assert game.may_jump()
    assert game.execute("jump foyer").lines[0].text.startswith(
        "The building rearranges"
    )
    data["totals"] = {
        "rooms": len(ROOMS), "puzzles": len(PUZZLES),
        "items": len(ITEMS), "findables": game.findable(),
        "curiosities": len(CURIOSITIES), "sigils": len(SIGILS),
        "points": game.possible(),
    }

out = Path(__file__).with_name("game.js")
out.write_text(
    "/* Generated by extract.py from upstream; Apache-2.0, Barry Warsaw. */\n"
    + "window.GAME = " + json.dumps(data, ensure_ascii=False, indent=2)
    .replace("</", "<\\/") + ";\n",
    encoding="utf-8",
)
print("Wrote", out, "with", data["totals"], "from", data["commit"][:10])
