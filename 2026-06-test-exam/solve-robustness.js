const baseline = [-1.39, -1.32, -2.26, -0.91];
let best = null;

for (let mask = 0; mask < 2 ** fragments.length; mask++) {
  let wc = 0;
  const scores = [...baseline];
  for (let index = 0; index < fragments.length; index++) {
    if (!(mask & (1 << index))) continue;
    wc += fragments[index][0];
    for (let model = 0; model < 4; model++) scores[model] += fragments[index][model + 1];
  }
  for (const [a, b, bonus] of pairs) {
    if ((mask & (1 << (a - 1))) && (mask & (1 << (b - 1)))) {
      for (let model = 0; model < 4; model++) scores[model] += bonus;
    }
  }
  const accuracies = scores.map((score) => 1 / (1 + Math.exp(-score)));
  const mean = accuracies.reduce((total, score) => total + score, 0) / accuracies.length;
  const floor = Math.min(...accuracies);
  if (mean < 0.97 || floor < 0.92) continue;
  if (!best || wc < best.wc || (wc === best.wc && mean > best.mean)) {
    best = { mask, wc, scores, mean, floor };
  }
}

